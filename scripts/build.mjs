#!/usr/bin/env node
/**
 * Builds the shipped files from src/, with no dependencies:
 *
 *   dist/order-button.js        ES module (the source plus a license line)
 *   dist/order-button.iife.js   classic <script>: sets window.OrderButton and
 *                               starts from <script type="application/json" data-order-button>
 *   dist/order-button.css       the optional styles
 *   .claude/skills/menu-from-photo/check-menu.mjs
 *                               the menu checker, with validateConfig() copied from src
 *
 *   node scripts/build.mjs           write the files and print their sizes
 *   node scripts/build.mjs --check   fail if any file is out of date (used by the tests)
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8').replace(/\r\n/g, '\n');

/** Every output file as { relativePath: content }. */
export function buildOutputs() {
  const pkg = JSON.parse(read('package.json'));
  const src = read('src/order-button.js');
  const css = read('src/order-button.css');

  const m = src.match(/export const VERSION = '([^']+)'/);
  if (!m || m[1] !== pkg.version) throw new Error(`VERSION in src/order-button.js (${m && m[1]}) must match package.json (${pkg.version}).`);

  const banner = `/*! order-button v${pkg.version} | MIT License | Copyright (c) 2026 Halvex Labs | https://github.com/counterkit/order-button */\n`;

  // IIFE: drop the `export` keywords and return the exported names.
  const names = [];
  const body = src.replace(/^export (async function|function|const|let|class) ([A-Za-z_$][\w$]*)/gm, (_, kind, name) => {
    names.push(name);
    return `${kind} ${name}`;
  });
  if (/^\s*export\b/m.test(body)) throw new Error('src/order-button.js uses an export form the IIFE build does not handle. Use `export function` or `export const` only.');
  const iife =
    banner +
    'var OrderButton = (function () {\n' +
    "'use strict';\n" +
    body.trimEnd() +
    '\n\nautoInit();\n\nreturn {\n' +
    names.map((n) => `  ${n}: ${n},`).join('\n') +
    '\n};\n})();\n';

  // Standalone menu checker for the Claude Code skill.
  const region = src.match(/\/\/ #region validate[^\n]*\n([\s\S]*?)\/\/ #endregion validate/);
  if (!region) throw new Error('validate region not found in src/order-button.js');
  const checker = `#!/usr/bin/env node
// check-menu.mjs: checks an order-button menu file and explains any problems.
//
//   node check-menu.mjs menu.json [more.json ...]
//
// Exit code 0 = no errors (warnings are allowed), 1 = errors, 2 = file missing or not JSON.
// Generated by scripts/build.mjs from src/order-button.js (order-button v${pkg.version}). Do not edit by hand.
// MIT License. Copyright (c) 2026 Halvex Labs. https://github.com/counterkit/order-button
import fs from 'node:fs';

${region[1].trimEnd()}

/** Every "_note" in the file, with where it is: the skill uses them to flag readings to double-check. */
function notes(config) {
  const out = [];
  const walk = (v, p) => {
    if (Array.isArray(v)) v.forEach((x, i) => walk(x, \`\${p}[\${i}]\`));
    else if (v && typeof v === 'object') {
      if (typeof v._note === 'string') out.push(\`\${p || '(top)'}\${typeof v.name === 'string' ? \` ("\${v.name}")\` : ''}: \${v._note}\`);
      for (const [k, x] of Object.entries(v)) if (k !== '_note') walk(x, p ? \`\${p}.\${k}\` : k);
    }
  };
  walk(config, '');
  return out;
}

const files = process.argv.slice(2);
if (!files.length) {
  console.log('Usage: node check-menu.mjs <menu.json> [more.json ...]');
  process.exit(2);
}
let code = 0;
for (const file of files) {
  let config;
  try {
    config = JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\\uFEFF/, ''));
  } catch (e) {
    console.log(\`\${file}: \${e.code === 'ENOENT' ? 'file not found' : \`not valid JSON (\${e.message})\`}.\`);
    code = 2;
    continue;
  }
  const { errors, warnings } = validateConfig(config);
  const cats = (config && config.menu && Array.isArray(config.menu.categories) && config.menu.categories) || [];
  const items = cats.flatMap((c) => (c && Array.isArray(c.items) ? c.items : []));
  const sized = items.filter((i) => i && Array.isArray(i.variants) && i.variants.length).length;
  const review = notes(config);
  console.log(\`\${file}: \${errors.length ? \`\${errors.length} error\${errors.length === 1 ? '' : 's'}\` : 'OK'}. \${cats.length} categories, \${items.length} items\${sized ? \`, \${sized} with sizes\` : ''}.\`);
  for (const e of errors) console.log(\`  error    \${e}\`);
  for (const w of warnings) console.log(\`  warning  \${w}\`);
  for (const n of review) console.log(\`  check    \${n}\`);
  if (errors.length && code === 0) code = 1;
}
process.exit(code);
`;

  return {
    'dist/order-button.js': banner + src,
    'dist/order-button.iife.js': iife,
    'dist/order-button.css': banner + css,
    '.claude/skills/menu-from-photo/check-menu.mjs': checker,
  };
}

/**
 * Minified copies, made with esbuild (a devDependency; the shipped files have
 * no dependencies). Returns {} when esbuild is not installed.
 */
export async function buildMinified(outputs = buildOutputs()) {
  let esbuild;
  try {
    esbuild = await import('esbuild');
  } catch {
    return {};
  }
  const banner = outputs['dist/order-button.js'].split('\n')[0] + '\n';
  const min = (code, extra) => banner + esbuild.transformSync(code, { minify: true, target: 'es2020', legalComments: 'none', charset: 'utf8', ...extra }).code;
  return {
    'dist/order-button.min.js': min(outputs['dist/order-button.js'], { format: 'esm' }),
    'dist/order-button.iife.min.js': min(outputs['dist/order-button.iife.js'], {}),
    'dist/order-button.min.css': min(outputs['dist/order-button.css'], { loader: 'css', target: ['chrome105', 'safari15.4', 'firefox121'] }),
  };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes('--check');
  const base = buildOutputs();
  const minified = await buildMinified(base);
  if (!Object.keys(minified).length) console.log('esbuild is not installed (run npm install), so the .min files were not touched.');
  const outputs = { ...base, ...minified };
  let stale = 0;
  for (const [rel, content] of Object.entries(outputs)) {
    const file = path.join(ROOT, rel);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
    if (check) {
      if (current !== content) {
        console.log(`out of date: ${rel}`);
        stale++;
      }
      continue;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    const raw = Buffer.byteLength(content);
    const gz = zlib.gzipSync(content, { level: 9 }).length;
    console.log(`${rel.padEnd(48)} ${(raw / 1024).toFixed(1).padStart(6)} KB   ${(gz / 1024).toFixed(1).padStart(5)} KB gzip`);
  }
  if (check) {
    if (stale) {
      console.log('Run `npm run build` and commit the result.');
      process.exit(1);
    }
    console.log('dist/ and the skill checker are up to date.');
  }
}
